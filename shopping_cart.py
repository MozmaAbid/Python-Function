shopping_cart = ["Egg","Bread","Milk","Meat","Rice"]

#append method
shopping_cart.append("Butter")
print(shopping_cart)

#insert method
shopping_cart.insert(1,"Green Tea")
print(shopping_cart)

#remove method
shopping_cart.remove("Meat")
print(shopping_cart)

#pop method
shopping_cart.pop(4)
print(shopping_cart)